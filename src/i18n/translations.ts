export type Language = 'en' | 'zh' | 'zh-CN'

export const LANGUAGES: readonly Language[] = ['en', 'zh', 'zh-CN']

/** Cycle order for the language toggle: EN → 繁中 → 简体 → EN. */
export function nextLanguage(lang: Language): Language {
  return lang === 'en' ? 'zh' : lang === 'zh' ? 'zh-CN' : 'en'
}

/** True for every Chinese variant — UI copy switches on this, not the exact locale. */
export function isZh(lang: Language): boolean {
  return lang !== 'en'
}

/** BCP47 locale for date/number formatting per UI language. */
export function langLocale(lang: Language): string {
  return lang === 'en' ? 'en-US' : lang === 'zh' ? 'zh-TW' : 'zh-CN'
}

/** Value for <html lang> per UI language. */
export function htmlLangFor(lang: Language): string {
  return lang === 'en' ? 'en' : lang === 'zh' ? 'zh-HK' : 'zh-CN'
}

/** The key a bilingual `{ en, zh }` data structure (services, legal, blog
 *  fields) is read with for this UI language — zh-CN shares the zh content. */
export function copyKey(lang: Language): 'en' | 'zh' {
  return lang === 'en' ? 'en' : 'zh'
}

